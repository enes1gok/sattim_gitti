import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";
import { createHash } from "node:crypto";

const dataRoot = new URL("../data/vehiclesdb/", import.meta.url);
const defaultOutput = fileURLToPath(new URL("../../supabase/seed.sql", import.meta.url));

// Quoting the entire JSON value keeps names such as O'... as data, never SQL.
const jsonSql = (value) => `'${JSON.stringify(value).replaceAll("'", "''")}'::jsonb`;

export function validateCatalog(catalog) {
  if (catalog.version !== "2026.10.4" || catalog.makes.length !== 315 || catalog.models.length !== 5541) {
    throw new Error("Unexpected VehiclesDB snapshot; review counts and licence before updating.");
  }
  const makes = new Set();
  const models = new Set();
  const naturalKeys = new Set();
  for (const make of catalog.makes) {
    if (!make.slug || !make.name || makes.has(make.slug)) throw new Error("Invalid or duplicate make");
    makes.add(make.slug);
  }
  for (const model of catalog.models) {
    const naturalKey = `${model.make_slug}/${model.slug}`;
    if (!makes.has(model.make_slug) || !model.name || !model.slug || models.has(model.source_key) || naturalKeys.has(naturalKey)) {
      throw new Error("Invalid, duplicate or orphaned model");
    }
    for (const field of ["body_types", "aliases", "observed_countries", "evidence_sources"]) {
      if (!Array.isArray(model[field]) || !model[field].every((value) => typeof value === "string")) throw new Error(`Invalid ${field}`);
    }
    models.add(model.source_key);
    naturalKeys.add(naturalKey);
  }
}

export function buildCatalogSql(catalog, source, supplement) {
  validateCatalog(catalog);
  const sources = [source, supplement.source];
  const makes = [
    ...catalog.makes.map((make) => ({ ...make, source_id: source.id, source_key: make.slug, source_version: catalog.version })),
    ...supplement.makes,
  ];
  const models = [
    ...catalog.models.map((model) => ({ ...model, source_id: source.id, source_version: catalog.version })),
    ...supplement.models,
  ];
  return `-- Generated by npm run catalog:prepare. Do not hand-edit.
-- Vehicle data by VehiclesDB (https://vehiclesdb.com), CC BY 4.0.
-- Turkish supplement: factual model names from the manufacturer's history.
-- No model years, engine specifications, listings or prices are inferred.
begin;

insert into public.vehicle_catalog_sources (id, name, url, license, version, attribution, metadata)
select id, name, url, license, version, attribution, metadata
from jsonb_to_recordset(${jsonSql(sources)}) as s(id text, name text, url text, license text, version text, attribution text, metadata jsonb)
on conflict (id) do update set name = excluded.name, url = excluded.url,
  license = excluded.license, version = excluded.version, attribution = excluded.attribution,
  metadata = excluded.metadata, imported_at = now();

insert into public.vehicle_makes (slug, name, source_id, source_key, source_version)
select slug, name, source_id, source_key, source_version
from jsonb_to_recordset(${jsonSql(makes)}) as m(slug text, name text, source_id text, source_key text, source_version text)
on conflict (slug) do update set name = excluded.name, source_key = excluded.source_key,
  source_version = excluded.source_version
where vehicle_makes.source_id = excluded.source_id;

insert into public.vehicle_models (make_id, slug, name, body_types, aliases, observed_countries, evidence_sources, source_id, source_key, source_version)
select mk.id, m.slug, m.name, m.body_types, m.aliases, m.observed_countries, m.evidence_sources, m.source_id, m.source_key, m.source_version
from jsonb_to_recordset(${jsonSql(models)}) as m(make_slug text, slug text, name text, body_types text[], aliases text[], observed_countries text[], evidence_sources text[], source_id text, source_key text, source_version text)
join public.vehicle_makes mk on mk.slug = m.make_slug
on conflict (make_id, slug) do update set name = excluded.name, body_types = excluded.body_types,
  aliases = excluded.aliases, observed_countries = excluded.observed_countries,
  evidence_sources = excluded.evidence_sources, source_key = excluded.source_key,
  source_version = excluded.source_version
where vehicle_models.source_id = excluded.source_id;

commit;
select (select count(*) from public.vehicle_makes) as makes,
  (select count(*) from public.vehicle_models) as models;
`;
}

export async function prepareCatalog(output = defaultOutput) {
  const load = async (name) => JSON.parse(await readFile(new URL(name, dataRoot), "utf8"));
  const [catalog, manifest, snapshot, supplement, attribution] = await Promise.all([
    load("catalog.json"), load("manifest.json"), load("snapshot.json"), load("turkey-supplement.json"),
    readFile(new URL("ATTRIBUTION.md", dataRoot), "utf8"),
  ]);
  const catalogBytes = await readFile(new URL("catalog.json", dataRoot));
  if (createHash("sha256").update(catalogBytes).digest("hex") !== snapshot.catalog_sha256) throw new Error("Catalogue hash mismatch");
  const source = {
    id: "vehiclesdb", name: "VehiclesDB", url: "https://vehiclesdb.com",
    license: manifest.license, version: manifest.version, attribution,
    metadata: { ...snapshot, upstream_sources: manifest.sources, scope: "Passenger-car make/model names; not a complete Turkish-market catalogue. No year/trim evidence." },
  };
  if (manifest.license !== "CC-BY-4.0" || manifest.version !== catalog.version) throw new Error("Snapshot licence/version mismatch");
  await writeFile(output, buildCatalogSql(catalog, source, supplement));
  return output;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  console.log(`Prepared ${await prepareCatalog(process.argv[2])}`);
}
